const crypto = require('crypto');
const { google } = require('googleapis');
require('dotenv').config();

// Per-user Google auth.
//
// Each user's Google refresh token is encrypted (AES-256-GCM) into an opaque session token
// that only the user's browser holds and sends as "Authorization: Bearer <token>".
// The server stores no credentials, so sessions survive restarts/redeploys and users never
// share a Google account.

const SCOPES = ['https://www.googleapis.com/auth/calendar'];

let secret = process.env.SESSION_SECRET;
if (!secret) {
  // Dev fallback: sessions stop working after a restart. Always set SESSION_SECRET in production.
  secret = crypto.randomBytes(32).toString('hex');
  console.warn('⚠️  SESSION_SECRET not set. Using a random key; users must reconnect after each restart.');
}
const KEY = crypto.createHash('sha256').update(secret).digest();

const createOAuthClient = () => new google.auth.OAuth2(
  process.env.GOOGLE_CLIENT_ID,
  process.env.GOOGLE_CLIENT_SECRET,
  process.env.REDIRECT_URI
);

// state is a random value generated by the browser; it comes back in the redirect so the
// frontend can confirm the login was started by this browser (login-CSRF protection).
function getAuthUrl(state) {
  return createOAuthClient().generateAuthUrl({
    access_type: 'offline',
    prompt: 'consent', // always return a refresh_token, even for returning users
    include_granted_scopes: true,
    scope: SCOPES,
    state,
  });
}

async function exchangeCode(code) {
  const { tokens } = await createOAuthClient().getToken(code);
  return tokens;
}

// ---- Session token sealing ----

function sealSession(payload) {
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', KEY, iv);
  const data = Buffer.concat([cipher.update(JSON.stringify(payload), 'utf8'), cipher.final()]);
  return Buffer.concat([iv, cipher.getAuthTag(), data]).toString('base64url');
}

function unsealSession(token) {
  try {
    const buf = Buffer.from(String(token), 'base64url');
    if (buf.length < 29) return null;
    const decipher = crypto.createDecipheriv('aes-256-gcm', KEY, buf.subarray(0, 12));
    decipher.setAuthTag(buf.subarray(12, 28));
    const json = Buffer.concat([decipher.update(buf.subarray(28)), decipher.final()]).toString('utf8');
    const payload = JSON.parse(json);
    return payload && payload.v === 1 && typeof payload.rt === 'string' ? payload : null;
  } catch {
    return null; // tampered, malformed, or sealed with a different SESSION_SECRET
  }
}

const createSessionToken = (refreshToken) =>
  sealSession({ v: 1, rt: refreshToken, iat: Date.now() });

// ---- One-time login codes ----
// The callback redirects to the frontend with a short-lived code instead of the session token,
// so the long-lived credential never appears in a URL.

const LOGIN_CODE_TTL_MS = 2 * 60 * 1000;
const loginCodes = new Map(); // code -> { sessionToken, expires }

function issueLoginCode(sessionToken) {
  const now = Date.now();
  for (const [c, v] of loginCodes) if (v.expires < now) loginCodes.delete(c);
  const code = crypto.randomBytes(24).toString('base64url');
  loginCodes.set(code, { sessionToken, expires: now + LOGIN_CODE_TTL_MS });
  return code;
}

function redeemLoginCode(code) {
  const entry = loginCodes.get(code);
  loginCodes.delete(code); // single use
  return entry && entry.expires >= Date.now() ? entry.sessionToken : null;
}

// ---- Per-request Google clients ----
// Cache one OAuth client per session so access tokens are reused until they expire
// (googleapis refreshes them automatically from the refresh token).

const MAX_CACHED_CLIENTS = 500;
const clientCache = new Map(); // sha256(token) -> OAuth2 client

const cacheKey = (token) => crypto.createHash('sha256').update(token).digest('hex');

function getClientForToken(token) {
  const session = unsealSession(token);
  if (!session) return null;
  const key = cacheKey(token);
  let client = clientCache.get(key);
  if (client) {
    clientCache.delete(key); // move to most-recent position
  } else {
    client = createOAuthClient();
    client.setCredentials({ refresh_token: session.rt });
    if (clientCache.size >= MAX_CACHED_CLIENTS) {
      clientCache.delete(clientCache.keys().next().value);
    }
  }
  clientCache.set(key, client);
  return client;
}

function forgetToken(token) {
  clientCache.delete(cacheKey(token));
}

const getBearerToken = (req) => {
  const header = req.headers.authorization || '';
  const match = header.match(/^Bearer\s+(.+)$/i);
  return match ? match[1].trim() : null;
};

// Attaches req.googleAuth (OAuth2 client) when a valid session token is present.
function attachGoogleAuth(req, res, next) {
  const token = getBearerToken(req);
  req.sessionToken = token;
  req.googleAuth = token ? getClientForToken(token) : null;
  next();
}

// Use on routes that need Google Calendar.
function requireGoogleAuth(req, res, next) {
  if (!req.googleAuth) {
    return res.status(401).json({ error: 'Google Calendar not connected', code: 'auth_required' });
  }
  next();
}

// True when Google rejects the refresh token (revoked, expired, or password changed).
const isAuthError = (err) => {
  const status = err?.response?.status || err?.code;
  const reason = err?.response?.data?.error;
  return reason === 'invalid_grant' || status === 401;
};

async function revokeToken(token) {
  const session = unsealSession(token);
  forgetToken(token);
  if (session) {
    try {
      await createOAuthClient().revokeToken(session.rt);
    } catch (e) {
      console.warn('Token revoke failed (may already be revoked):', e?.response?.data || e.message);
    }
  }
}

module.exports = {
  getAuthUrl,
  exchangeCode,
  createSessionToken,
  issueLoginCode,
  redeemLoginCode,
  attachGoogleAuth,
  requireGoogleAuth,
  isAuthError,
  forgetToken,
  revokeToken,
};
